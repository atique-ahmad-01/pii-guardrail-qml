"""Phase 2: build the stress-test sets from the processed test split.

Needs ``scripts/prepare_data.py`` to have run for the same config. Writes parquet files and a
``stress_card.md`` to ``<data_dir>/stress/``.

Usage: python scripts/run_stress.py --config configs/smoke.yaml
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

import pandas as pd

from piiguard.data.context_examples import build_context_docs
from piiguard.data.load import docs_to_frame, frame_to_docs, label_counts
from piiguard.data.stress import (
    build_obfuscated,
    build_rare,
    rare_labels,
    validate_doc,
)
from piiguard.utils import ensure_dir, get_logger, load_config, set_seed, timed, write_run_record

log = get_logger("run_stress")


def md_table(header: list[str], rows: list[list]) -> str:
    """Render a Markdown table."""
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    args = ap.parse_args()
    cfg = load_config(args.config)
    seed, data_dir = cfg["seed"], Path(cfg["paths"]["data_dir"])
    scfg = cfg["stress"]
    set_seed(seed)
    out_dir = ensure_dir(data_dir / "stress")

    train = frame_to_docs(pd.read_parquet(data_dir / "train.parquet"))
    test = frame_to_docs(pd.read_parquet(data_dir / "test.parquet"))
    sets: dict[str, list[dict]] = {}
    timings: dict[str, float] = {}

    with timed() as t:
        # ---- obfuscation: one set per transform plus a combined one
        for i, kind in enumerate([*scfg["obfuscation_kinds"], "all"]):
            sets[f"obf_{kind}"] = build_obfuscated(test, kind, seed + 10 + i)
        # ---- rare types
        rare, testable, untestable = rare_labels(
            label_counts(train),
            label_counts(test),
            scfg["rare_label_fraction"],
            scfg["min_test_support"],
        )
        sets["rare"] = build_rare(test, testable)
        # ---- context-only (synthetic, hand-written)
        sets["context_only"] = build_context_docs()
    timings["build_s"] = t.elapsed

    # ---- validate every doc, write parquet
    for name, docs in sets.items():
        bad = {d["id"]: p for d in docs if (p := validate_doc(d))}
        if bad:
            raise AssertionError(
                f"{name}: invalid spans in {len(bad)} docs, e.g. {next(iter(bad.items()))}"
            )
        docs_to_frame(docs).to_parquet(out_dir / f"{name}.parquet", index=False)
    (out_dir / "rare_labels.json").write_text(
        json.dumps({"rare": rare, "testable": testable, "untestable": untestable}, indent=2)
    )

    # ---- card
    rows = []
    for name, docs in sets.items():
        changed = sum(d.get("n_changed", 0) for d in docs)
        rows.append([name, len(docs), sum(len(d["spans"]) for d in docs), changed or "-"])
    cross = {
        k: len(pd.read_parquet(data_dir / f"cross_{k}.parquet"))
        for k in cfg["data"]["stress_langs"]
    }
    train_counts, test_counts = label_counts(train), label_counts(test)
    rare_rows = [
        [lab, train_counts.get(lab, 0), test_counts.get(lab, 0), "yes" if lab in testable else "NO"]
        for lab in rare
    ]
    # an example before/after for each obfuscation kind (from the data, not invented)
    examples = []
    src = {d["id"]: d for d in test}
    for kind in [*scfg["obfuscation_kinds"]]:
        docs = sets[f"obf_{kind}"]
        if docs:
            d = docs[0]
            orig = src[d["source_id"]]
            changed = [
                (o["value"], n["value"])
                for o, n in zip(orig["spans"], d["spans"], strict=True)
                if o["value"] != n["value"]
            ]
            examples.append([kind, "; ".join(f"`{a}` -> `{b}`" for a, b in changed[:3])])
    card = f"""# Stress-set card ({cfg["profile"]} profile)

Generated by `scripts/run_stress.py` from `test.parquet` only. Seed {seed}. Every document passes
`validate_doc`: spans are in bounds, sorted, disjoint, and `text[start:end] == value`.

## Sets
{md_table(["set", "docs", "gold spans", "edits applied"], rows)}

Cross-lingual sets (built in Phase 1, never trained on): {cross}.

## Obfuscation: first changed spans per transform
{md_table(["transform", "examples"], examples)}

## Rare types
The least frequent {scfg["rare_label_fraction"]:.0%} of labels by **train** frequency
(ceil(fraction * n_labels) = {len(rare)} labels). A rare label with fewer than
{scfg["min_test_support"]} test spans is untestable and is left out of the set. The `rare` set keeps
every span of each selected document; the `eval_labels` column lists the labels to score.

{md_table(["label", "train spans", "test spans", "testable"], rare_rows)}

## Context-only (synthetic)
{len(sets["context_only"])} hand-written examples (`context_examples.py`) where a person is
identifiable without a direct identifier. All people and places are invented.
Gold = the identifying phrase,
label `CONTEXT_ID`, scored type-agnostically. **Awaiting owner review.**
"""
    (out_dir / "stress_card.md").write_text(card)
    metrics = {
        "sets": {n: len(d) for n, d in sets.items()},
        "rare": {"rare": rare, "testable": testable, "untestable": untestable},
        "edits": {n: sum(d.get("n_changed", 0) for d in docs) for n, docs in sets.items()},
        "label_counts_rare_test": {lab: test_counts.get(lab, 0) for lab in rare},
        "cross_lingual_docs": cross,
    }
    rec = write_run_record(
        Path(cfg["paths"]["results_dir"]) / "stress",
        "build_stress",
        config=cfg,
        seed=seed,
        metrics=metrics,
        timings=timings,
    )
    log.info("sets: %s", {n: len(d) for n, d in sets.items()})
    log.info("untestable rare labels: %s", untestable)
    log.info("wrote %s and %s", out_dir / "stress_card.md", rec)
    _ = Counter  # keep import used for type clarity in future extensions


if __name__ == "__main__":
    main()
